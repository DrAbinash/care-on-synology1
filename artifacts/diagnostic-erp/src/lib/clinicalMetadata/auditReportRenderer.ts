/**
 * Renders the anatomy metadata audit as the Markdown the readiness review is
 * read in. Pure string building: no file system, no imports from the app, so it
 * can be exercised by the audit's own test suite and cannot fail silently the
 * way an untested rule once did.
 */
import type { AuditResult, OrderingFeasibility } from "./anatomyMetadataAudit";

const pct = (n: number, d: number): string => (d > 0 ? `${((n / d) * 100).toFixed(1)}%` : "n/a");

const cell = (v: string | number): string => String(v).replace(/\|/g, "\\|");

function table(headers: readonly string[], rows: readonly (readonly (string | number)[])[]): string {
  const head = `| ${headers.join(" | ")} |`;
  const rule = `| ${headers.map(() => "---").join(" | ")} |`;
  const body = rows.map((r) => `| ${r.map(cell).join(" | ")} |`);
  return [head, rule, ...body].join("\n");
}

const RULE_MEANING: Record<string, string> = {
  "C3-R01": "findings tile with no canonical concept",
  "C3-R02": "concept resolves to no content pack",
  "C3-R03": "findings tile with no anatomical section",
  "C3-R04": "section not declared by this examination's baseline",
  "C3-R05": "canonical concept declared twice",
  "C3-R06": "alias claimed by more than one concept",
  "C3-R07": "concept repeats inside one baseline manifest",
  "C3-R08": "anatomical level that does not exist",
  "C3-R09": "laterality value outside the accepted set",
  "C3-R10": "baselineReplaces target not rendered by the baseline",
  "C3-R10a": "findings tile with no conflict group",
  "C3-R11": "sentence requires a token the parameter contract does not know",
  "C3-R11b": "sentence ships an unfilled measurement blank",
  "C3-R13": "tile sentence is more than one sentence",
  "C3-R14": "Findings Library and baseline section vocabularies diverge",
  "C3-R15": "prose names a level with no level metadata",
  "C3-R16": "substitution token stored in anatomical_section",
  "C3-R17": "seeded table has no concept column",
  "C3-R18": "seeded rows carry no anatomical section",
  "C3-R19": "seeded rows declare no conflict group",
  "C3-R20": "examination has no owned baseline manifest",
  "C3-R21": "seed SQL rows the parser could not read",
  "C3-R22": "two baseline observations own one slot",
  "C3-R23": "one concept filed under several conflict groups",
  "C3-R24": "requested examination has no findings tile at all",
};

export function renderAuditReport(
  result: AuditResult,
  feasibility: OrderingFeasibility,
  source: { revision: string; generatedBy: string },
): string {
  const out: string[] = [];
  out.push("# CARE clinical metadata audit — anatomy readiness (C3)");
  out.push("");
  out.push(`Generated by \`${source.generatedBy}\` from repository source data at \`${source.revision}\`.`);
  out.push("");
  out.push("Nothing here changes how a report is composed. Every count is measured from the files "
    + "listed in `docs/clinical/C3_ANATOMICAL_METADATA_REVIEW.md`; none is typed in by hand.");
  out.push("");

  out.push("## 1. Inventory");
  out.push("");
  out.push(table(["measure", "count"], [
    ["Quick Select tiles in the catalogue", result.totals.tiles],
    ["of which findings tiles (the ones anatomy would order)", result.totals.findingsTiles],
    ["findings tiles whose concept resolves to a content pack", result.totals.conceptBearingTiles],
    ["findings tiles whose concept also appears in that exam's baseline", result.totals.manifestMappedTiles],
    ["content packs", result.totals.packs],
    ["owned baseline manifests", result.totals.manifests],
    ["seeded quick-finding rows read from migrations", result.seeds.reduce((s, x) => s + x.rowCount, 0)],
  ]));
  out.push("");
  out.push(table(["severity", "findings"], [
    ["ERROR", result.counts.ERROR],
    ["WARNING", result.counts.WARNING],
    ["INFORMATIONAL", result.counts.INFORMATIONAL],
    ["REQUIRES_RADIOLOGIST_REVIEW", result.counts.REQUIRES_RADIOLOGIST_REVIEW],
  ]));
  out.push("");

  out.push("## 2. Can observations be ordered by anatomy today? (Phase F measurement)");
  out.push("");
  out.push("A tile has a *safe rank key* only when its concept resolves, its `anatomicalSection` is one "
    + "the examination's own baseline manifest declares, and that examination has a manifest at all. "
    + "Anything less would mean inferring placement from English prose.");
  out.push("");
  out.push(table(["bucket", "tiles", "share of findings tiles"], [
    ["safe rank key today", feasibility.safeRankKey, pct(feasibility.safeRankKey, feasibility.findingsTiles)],
    ["concept known, placement needs a clinical mapping", feasibility.needsClinicalMapping, pct(feasibility.needsClinicalMapping, feasibility.findingsTiles)],
    ["no ordering key at all", feasibility.noOrderingKey, pct(feasibility.noOrderingKey, feasibility.findingsTiles)],
  ]));
  out.push("");
  out.push(table(["other measured quantity", "value"], [
    ["tiles whose sentence is more than one sentence", feasibility.multiSentenceTiles],
    ["tiles competing for one baseline sentence", feasibility.tilesSharingOneBaselineTarget],
    ["conflict groups holding both a normal and an abnormal tile", `${feasibility.conflictGroupsHoldingBothANormalAndAnAbnormal.length}: ${feasibility.conflictGroupsHoldingBothANormalAndAnAbnormal.join(", ")}`],
    ["examinations with an owned baseline manifest", feasibility.examsWithOwnedBaseline],
    ["examinations measured with none", feasibility.examsWithoutOwnedBaseline],
  ]));
  out.push("");

  out.push("## 3. Coverage by examination (Phase C)");
  out.push("");
  out.push("`section` counts tiles whose section is one the examination's baseline declares. "
    + "`baseline` counts tiles whose concept appears in that baseline. A row with `tiles = 0` means the "
    + "catalogue has no findings tile for that examination — the audit looked and there is nothing there.");
  out.push("");
  out.push(table(
    ["scope", "tiles", "concept", "resolves", "section", "conflict", "replaces", "baseline", "unplaced"],
    result.coverage.map((c) => [
      c.scope, c.tiles, c.withConcept, c.conceptResolves, c.sectionKnown,
      c.withConflictGroup, c.withBaselineReplaces, c.mappedToManifestConcept, c.unresolvedPlacement,
    ]),
  ));
  out.push("");

  out.push("## 4. Owned baseline manifests (Phase D)");
  out.push("");
  out.push("Array order in each manifest is the only anatomical order CARE has approved so far. "
    + "These are the sequences an ordering engine could rank against.");
  out.push("");
  out.push(table(
    ["manifest", "exam", "revision", "findings rows", "distinct concepts", "repeating", "sections in order"],
    result.manifests.map((m) => [
      m.name, `${m.modality}/${m.bodyPart}`, m.revision, m.findingsObservationCount,
      m.distinctConcepts, m.repeatingConcepts.join(", ") || "—", m.sectionsInOrder.join(" → "),
    ]),
  ));
  out.push("");

  out.push("## 5. Seeded database rows (radiology_quick_findings, from migrations only)");
  out.push("");
  out.push("Read from checked-in SQL — the audit never opens a database. These rows do reach one "
    + "live surface: `GET /api/radiology/quick-select` returns the whole table "
    + "(`api-server/src/routes/radiologyQuickFindings.ts:56`) and `QuickFindingsPanel.tsx` renders it, "
    + "while the reporting canvas Quick Select strip reads the TypeScript catalogue instead "
    + "(`zai-workspace/store.ts:1100`). Two authoring surfaces, two metadata sources.");
  out.push("");
  out.push(table(
    ["file", "rows", "section", "conflict", "replaces", "template tokens in section", "unparsed", "concept column"],
    result.seeds.map((s) => [
      s.file, s.rowCount, s.section, s.conflictGroup, s.baselineReplaces,
      s.templateTokensInSection, s.unparsedRows,
      s.hasConceptColumn ? "yes" : "no",
    ]),
  ));
  out.push("");

  out.push("## 6. What the audit found, by rule");
  out.push("");
  const byRule = new Map<string, { severity: string; items: typeof result.findings }>();
  for (const f of result.findings) {
    const g = byRule.get(f.rule) ?? { severity: f.severity, items: [] };
    g.items.push(f);
    byRule.set(f.rule, g);
  }
  out.push(table(["rule", "severity", "count", "meaning"],
    [...byRule.entries()].sort((a, b) => a[0].localeCompare(b[0], undefined, { numeric: true }))
      .map(([rule, g]) => [rule, g.severity, g.items.length, RULE_MEANING[rule] ?? ""] )));
  out.push("");
  out.push("### Every finding, by rule");
  out.push("");
  out.push("These lines quote catalogue wording, so they live in this generated report and never in "
    + "the committed coverage snapshot, which carries counts only.");
  out.push("");
  for (const [rule, g] of [...byRule.entries()].sort((a, b) => a[0].localeCompare(b[0], undefined, { numeric: true }))) {
    out.push(`- **${rule}** (${g.severity}, ${g.items.length}) — ${RULE_MEANING[rule] ?? ""}`);
    for (const f of g.items) {
      out.push(`    - \`${f.subject}\`: ${f.detail}`);
    }
  }
  out.push("");
  out.push("The clinical decisions this raises are listed for approval in "
    + "`docs/clinical/C3_ANATOMICAL_METADATA_REVIEW.md`. Nothing there has been applied.");
  out.push("");
  return out.join("\n");
}
