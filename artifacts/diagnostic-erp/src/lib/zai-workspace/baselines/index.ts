export type OwnedBaselineCatalogEntry = {
  name: string;
  modality: "MR";
  bodyPart: string;
  protocolScope?: string;
  clinicalHistory: string;
  technique: string;
  findings: string;
  impression: string;
  recommendation: string;
  reportTitle: string;
  diagnosisTags: string[];
  manifest: BaselineManifest;
};

function asEntry(meta: OwnedBaselineCatalogEntry): OwnedBaselineCatalogEntry {
  return meta;
}

/** Phase 2 owned baseline catalog (8 formats) plus the Dorsal Standard Normal that was
 *  missing from it — without which a billed MRI Dorsal Spine report has no owned rows —
 *  and the Pelvis and Shoulder Standard Normals the owner instructed shipped in the
 *  final corrections round of PR #1077 (they were the measured manual gaps: tile-supported
 *  examinations that opened no complete normal).
 *
 *  The last three entries are the identities the coverage audit measured as library rows
 *  that DO open a complete normal but own none of its sentences: the contrast and epilepsy
 *  Brain normals and the LS Spine + Whole Spine Screening normal. Registering them here is
 *  what lets `baselineManifestForFormat` hand the same curated manifest to a server-hydrated
 *  copy of the row, so a Quick Select click retires the normal it falsifies instead of
 *  printing the two side by side.
 *
 *  The final entry is different in kind: the Dorso-Lumbar Standard Normal is the identity the
 *  audit measured as opening NO normal at all (`resolveNormalBootstrapFormat` answered
 *  `no-match` for region `Dorso-Lumbar Spine`, while its Quick Select strip already offered
 *  52 boxes). It is the only MRI spine examination in the booked vocabulary that
 *  `canonicalContentRegion` does not fold onto another region, so no other row could stand
 *  for it and no sentence of it existed to inherit. See `mriDorsoLumbarStandardNormal.ts` for
 *  where its seven statements come from. */
export function ownedBaselineCatalog(): OwnedBaselineCatalogEntry[] {
  return [
    asEntry(MRI_BRAIN_STANDARD_NORMAL_META),
    asEntry(MRI_CERVICAL_STANDARD_NORMAL_META),
    asEntry(MRI_DORSAL_STANDARD_NORMAL_META),
    asEntry(MRI_KNEE_STANDARD_NORMAL_META),
    asEntry(MRI_PELVIS_STANDARD_NORMAL_META),
    asEntry(MRI_SHOULDER_STANDARD_NORMAL_META),
    asEntry(MRI_BRAIN_SCREENING_NORMAL_META),
    asEntry(MRI_CERVICAL_SCREENING_NORMAL_META),
    asEntry(MRI_DORSAL_SCREENING_NORMAL_META),
    asEntry(MRI_LS_SCREENING_NORMAL_META),
    asEntry(MRI_WHOLE_SPINE_SCREENING_NORMAL_META),
    asEntry(MRI_BRAIN_CONTRAST_NORMAL_META),
    asEntry(MRI_BRAIN_EPILEPSY_NORMAL_META),
    asEntry(MRI_LS_WHOLE_SPINE_SCREENING_NORMAL_META),
    asEntry(MRI_DORSO_LUMBAR_STANDARD_NORMAL_META),
  ];
}

/** Built-in name → manifest map for hydration. */
export function ownedBaselineManifestByName(): Map<string, BaselineManifest> {
  const map = new Map<string, BaselineManifest>();
  for (const e of ownedBaselineCatalog()) map.set(e.name, e.manifest);
  return map;
}

export function ownershipCount(manifest: BaselineManifest): number {
  return manifest.observations.length;
}

export function formatLooksLikeOwnedBaseline(
  format: Pick<ReportFormat, "name" | "modality" | "bodyPart">,
): boolean {
  return ownedBaselineManifestByName().has(format.name);
}
