function cleanPhone(p: string | null): string | null {
  if (!p) return null;
  const digits = p.replace(/\D/g, "");
  // Treat all-zero or too-short strings as no phone
  if (!digits || /^0+$/.test(digits) || digits.length < 7) return null;
  return p.trim();
}

async function main() {
  console.log(`Processing ${RAW.length} referral doctor entries…`);

  // Step 1: deduplicate within the input list itself (keep first occurrence)
  const seen = new Set<string>();
  const candidates = RAW
    .filter(([name]) => {
      const key = name.trim().toUpperCase();
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .map(([name, phone, address]) => ({
      name: name.trim(),
      specialization: "Doctor",
      phone: cleanPhone(phone),
      hospitalAffiliation: address?.trim() || null,
    }));

  console.log(`After input deduplication: ${candidates.length} unique entries`);

  // Step 2: fetch names that already exist in the DB so we can skip them.
  // The doctors table has no UNIQUE index on name, so we cannot use
  // onConflictDoNothing. We fetch in batches to avoid a huge IN clause.
  const FETCH_CHUNK = 500;
  const existingNames = new Set<string>();
  for (let i = 0; i < candidates.length; i += FETCH_CHUNK) {
    const names = candidates.slice(i, i + FETCH_CHUNK).map((r) => r.name);
    const rows = await db
      .select({ name: doctorsTable.name })
      .from(doctorsTable)
      .where(inArray(doctorsTable.name, names));
    rows.forEach((r) => existingNames.add(r.name.toUpperCase()));
  }

  const toInsert = candidates.filter(
    (r) => !existingNames.has(r.name.toUpperCase()),
  );

  console.log(
    `Already in DB: ${existingNames.size} matched. Inserting ${toInsert.length} new entries…`,
  );

  if (toInsert.length === 0) {
    console.log("Nothing to insert — all doctors already exist.");
    process.exit(0);
  }

  // Step 3: batch insert
  const INSERT_CHUNK = 100;
  let inserted = 0;
  for (let i = 0; i < toInsert.length; i += INSERT_CHUNK) {
    const chunk = toInsert.slice(i, i + INSERT_CHUNK);
    const result = await db
      .insert(doctorsTable)
      .values(chunk)
      .returning({ id: doctorsTable.id });
    inserted += result.length;
    process.stdout.write(
      `  Inserted: ${inserted}/${toInsert.length}\r`,
    );
  }

  console.log(`\nDone. ${inserted} new doctors inserted.`);
  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
