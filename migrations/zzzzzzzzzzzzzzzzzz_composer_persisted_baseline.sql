-- PROMPT 4 / durable Composer Apply: store the server-derived report-content baseline on the job.
--
-- WHY THIS FILE EXISTS
-- The Composer's freshness evidence today is a set of hashes the *browser*
-- computed over the text in its editor (`source_findings_hash`,
-- `source_impression_hash`, `source_report_revision`, `input_hash`). Those
-- columns describe what the clinician's tab believed; none of them is derived
-- from what the database actually holds. `loadPersistedReportToken()` can
-- compute a server-side token from `patient_reports`, but a reporting-workspace
-- study has no `patient_reports` row at all until it is signed, so for every
-- live drafting session that axis returns `token: null` and is never bound to
-- the job for later comparison. The durable record of the editable report is
-- `radiology_report_drafts`, and nothing on the job pointed at it.
--
-- So Apply could be recorded as APPLIED before any of it was persisted, and
-- nothing could later tell "the report did not change" apart from "we never
-- looked". That is the defect this PR closes, and it needs three columns:
--
--   source_persisted_token  content token of the authoritative draft row when
--                           the job was enqueued — generated by the server from
--                           its own read, never supplied by the browser.
--   source_draft_id         the `radiology_report_drafts.id` that token was
--                           taken from (NULL when the study had no draft row).
--   applied_persisted_token content token of the row the server authorised as
--                           the Apply's own persistence step, written in that
--                           step's transaction. /applied marks APPLIED only when
--                           the row still carries this token.
--
-- WHAT THIS MIGRATION DELIBERATELY DOES NOT DO
--   * No NOT NULL, no default, no backfill. A column cannot be an evidence
--     trail if old rows can look like it. Every pre-existing job keeps NULL,
--     which the code reads as "no baseline was ever captured" and refuses on,
--     rather than as "nothing has changed". That distinction is the whole point
--     of the requirement "missing token must not mean unchanged".
--   * No new index: all three are read and written by job id, which is the
--     primary key, and the columns are never a query predicate.
--   * No change to `radiology_report_drafts`. Its content is hashed at read
--     time; storing a copy of a hash next to the text it came from would drift.
--   * No rewrite of any earlier migration. The chain is append-only because the
--     clinic's database has already run those files.
--
-- SAFE AGAINST THE CURRENT PRODUCTION SCHEMA
-- `ADD COLUMN IF NOT EXISTS` is a no-op on a database where `drizzle-kit push`
-- already created the columns, so a migration-built clinic database and a
-- development database converge on the same shape. The table itself is created
-- by `add_ai_report_composer.sql` (sorts first), so this file can never run
-- before its target exists; `node scripts/check-migration-order.cjs` proves it.

ALTER TABLE ai_report_compose_jobs
  ADD COLUMN IF NOT EXISTS source_persisted_token text;

ALTER TABLE ai_report_compose_jobs
  ADD COLUMN IF NOT EXISTS source_draft_id integer;

ALTER TABLE ai_report_compose_jobs
  ADD COLUMN IF NOT EXISTS applied_persisted_token text;
